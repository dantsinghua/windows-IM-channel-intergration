def _iso(ms: Optional[int]) -> Optional[str]:
    return iso8601(ms) if ms is not None else None


def _read_text(path: str) -> Optional[str]:
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            return f.read()
    except OSError:
        return None


class LinuxWslEnvReader:
    """#74 的 WSL 侧快照来源(只读 ``/proc`` / ``/sys`` / ``/etc``);读不到的项一律 ``None``,**不编造**。"""

    def __init__(self, *, proc: str = "/proc", sys: str = "/sys", etc: str = "/etc"):
        self.proc, self.sys, self.etc = proc, sys, etc

    def _default_iface(self) -> Optional[str]:
        raw = _read_text(os.path.join(self.proc, "net", "route"))
        if not raw:
            return None
        for line in raw.splitlines()[1:]:
            cols = line.split()
            if len(cols) >= 2 and cols[1] == "00000000":
                return cols[0]
        return None

    def snapshot(self) -> dict[str, Any]:
        iface = self._default_iface()
        mtu_raw = _read_text(os.path.join(self.sys, "class", "net", iface, "mtu")) if iface else None
        resolv = _read_text(os.path.join(self.etc, "resolv.conf"))
        nameservers = [ln.split()[1] for ln in (resolv or "").splitlines() if ln.startswith("nameserver") and len(ln.split()) > 1]
        generated = resolv is not None and "generated by WSL" in resolv
        pools: Optional[list[Any]] = None
        daemon = _read_text(os.path.join(self.etc, "docker", "daemon.json"))
        if daemon:
            try:
                pools = json.loads(daemon).get("default-address-pools")
            except ValueError:
                pools = None
        ksm_raw = _read_text(os.path.join(self.sys, "kernel", "mm", "ksm", "run"))
        zram_raw = _read_text(os.path.join(self.sys, "block", "zram0", "disksize"))
        return {
            "iface": iface,
            "mtu": int(mtu_raw.strip()) if (mtu_raw or "").strip().isdigit() else None,
            "resolv_conf": {"source": ("wsl_generated" if generated else "custom") if resolv is not None else None,
                            "nameservers": nameservers},
            "docker": {"default_address_pools": pools},
            "ksm": {"run": int(ksm_raw.strip()) if (ksm_raw or "").strip().isdigit() else None},
            "zram": {"disksize_mb": int(zram_raw.strip()) // 1048576 if (zram_raw or "").strip().isdigit() else None},
            "kernel_release": (_read_text(os.path.join(self.proc, "sys", "kernel", "osrelease")) or "").strip() or None,
        }


def register_ext(app: FastAPI, *, agent, cfg, prefix: str, principal, json_or_empty, caps_by_op) -> None:
    """把本模块的端点挂到 ``app``。

    ``principal(request, level)`` / ``json_or_empty(request)`` / ``caps_by_op`` 由 ``create_api`` 传入,
    保证鉴权、错误信封、审计、幂等走的都是**既有那一套**,本模块不另起炉灶。
    """
    P = prefix

    def _audit(p: Principal, action: str, *, result_code: str = "OK", detail: Optional[dict[str, Any]] = None,
               account_id: Optional[str] = None) -> None:
        try:
            agent.store.insert_audit(kind="api", transport=p.transport, actor=p.actor, action=action,
                                     account_id=account_id, result_code=result_code, detail=detail or {}, now_ms=agent.clock())
        except Exception as e:      # 审计失败不影响业务(与 create_api 的 middleware 同口径)
            log.warning("审计写入失败 action=%s: %s", action, e)

    async def _wa(method: str, path: str, *, json_body: Optional[dict[str, Any]] = None, timeout_s: float = 5.0,
                  missing_reason: Optional[str] = None, missing_hint: str = "") -> Optional[dict[str, Any]]:
        """转发到 WinAgent;``404`` 与「不可达 / 其它错」分成不同 reason(与 #76 的 `_wa_probes` 同口径)。"""
        try:
            status, body = await agent.winagent.request(method, path, json=json_body, timeout_s=timeout_s, retry=(method == "GET"))
        except Exception as e:
            raise ApiError(503, "NOT_READY", f"WinAgent 不可达:{e}", reason="winagent_offline", retryable=True)
        if status == 404 and missing_reason:
            raise ApiError(503, "NOT_READY", f"WinAgent 尚未提供该端点({missing_hint})", reason=missing_reason,
                           retryable=False, needs_human=True)
        if status >= 400:
            raise ApiError(503, "NOT_READY", f"WinAgent 回 {status}", reason="winagent_error", retryable=True)
        return body


    def _grace_put(app_id: str, blob: Optional[dict[str, Any]], actor: str) -> None:
        grace = agent.store.settings_get(GRACE_KEY) or {}
        if not isinstance(grace, dict):
            grace = {}
        now = agent.clock()
        grace = {k: v for k, v in grace.items()                         # 顺手把过期项清掉,免得越积越多
                 if isinstance(v, dict) and int(v.get("until_ms") or 0) > now and k != app_id}

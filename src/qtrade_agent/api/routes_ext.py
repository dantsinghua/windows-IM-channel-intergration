    # ================================================================== #75 探测(full / sample 两路)
    async def _probe_full(targets: list[str], *, trigger: str, detail: str) -> dict[str, Any]:
        """全量/指定目标探测:Windows 侧转 ``POST /wa/v1/probe``,WSL 侧走可注入的四级探测器。

        WSL 侧没有探测器(缺省)⇒ 该侧每个目标记 ``SKIPPED(agent_probe_disabled)``(04 §3.4 (df) 的开放项,
        **诚实记录,不假装探过**)。WSL 侧的结论经 ``PUT /wa/v1/probes`` 回写(真值只在 winagent.db)。
        """
        run_id = ulid(agent.clock())
        results: list[dict[str, Any]] = []
        try:
            wa_body = await _wa("POST", "/wa/v1/probe", json_body={"targets": targets or None, "trigger": trigger,
                                                                   "detail": detail, "run_id": run_id}, timeout_s=60.0)
            for row in (wa_body or {}).get("results") or []:
                results.append({**row, "side": row.get("side") or "windows"})
        except ApiError as e:
            results.append({"side": "windows", "target": None, "status": "SKIPPED", "level_reached": "none",
                            "detail": e.reason or "winagent_error"})
        probe: Optional[LevelProbe] = getattr(agent, "net_probe", None)
        wsl_rows: list[dict[str, Any]] = []
        for t in targets:
            if probe is None:
                wsl_rows.append({"side": "wsl", "target": t, "status": "SKIPPED", "level_reached": "none",
                                 "detail": "agent_probe_disabled"})
                continue
            try:
                out = await probe.probe(t, timeout_s=5.0)
            except Exception as e:
                out = {"status": "FAIL", "level_reached": "none", "detail": repr(e)[:200]}
            wsl_rows.append({"side": "wsl", "target": t, "run_id": run_id, **out})
        results += wsl_rows
        if wsl_rows and probe is not None:
            try:
                await _wa("PUT", "/wa/v1/probes", json_body={"run_id": run_id, "results": wsl_rows})
            except ApiError as e:
                log.warning("#75 WSL 侧结果回写失败(%s):结果照常同步返回,库里没有这一份", e.reason)
        return {"run_id": run_id, "results": results}

    @app.post(f"{P}/system/probe")
    async def system_probe(request: Request):
        """#75,级别 W。``mode`` 缺省 ``"probe"``(= 全量/指定目标四级探测,同步返回 ``{run_id, results}``);
        ``mode:"sample"``(C-1,04 §2.8.4)= 实测采样,返回逐字 ``{sampled_at, duration_s, rows, skipped}`` —— **没有 `run_id`**
        (sample 不产生 `probe_result`)。``mode:"full"`` 是 ``"probe"`` 的同义词(04 §3.4 用这个写法)。
        """
        p = principal(request, "write")
        body = await json_or_empty(request)
        mode = body.get("mode") or "probe"
        if mode not in ("probe", "full", "sample"):
            raise ApiError(400, "INVALID_ARGS", "mode 须为 probe|full|sample", reason="bad_mode",
                           extra={"details": [{"pointer": "/mode"}]})
        if mode == "sample":
            raw = body.get("duration_s", 10)
            try:
                duration = float(raw)
            except (TypeError, ValueError):
                raise ApiError(400, "INVALID_ARGS", "duration_s 须为数字", reason="bad_duration",
                               extra={"details": [{"pointer": "/duration_s"}]})
            if not (0 < duration <= PROBE_SAMPLE_MAX_S):
                raise ApiError(400, "INVALID_ARGS", f"duration_s 须在 (0, {PROBE_SAMPLE_MAX_S}]", reason="bad_duration",
                               extra={"details": [{"pointer": "/duration_s"}]})
            out = await agent.sample_observed(duration_s=duration)
            running = {r["channel"] for r in agent.store.list_accounts(state="running")}
            skipped = [{"channel": ch, "account_id": None, "reason": "no_running_account"}
                       for ch in ("qidian", "qq", "wechat") if ch not in running]
            _audit(p, "system.probe", detail={"mode": "sample", "duration_s": duration, "rows": len(out.get("rows") or [])})
            return {"ok": True, "sampled_at": out.get("sampled_at"), "duration_s": out.get("duration_s"),
                    "rows": out.get("rows") or [], "skipped": skipped}
        targets = body.get("targets") or []
        if not isinstance(targets, list) or any(not isinstance(t, str) or not t for t in targets):
            raise ApiError(400, "INVALID_ARGS", "targets 须为非空字符串数组(缺省 = 全量)", reason="bad_targets",
                           extra={"details": [{"pointer": "/targets"}]})
        trigger = body.get("trigger") or "manual"
        if trigger not in ("manual", "wizard", "install"):
            raise ApiError(400, "INVALID_ARGS", "trigger 须为 manual|wizard|install", reason="bad_trigger",
                           extra={"details": [{"pointer": "/trigger"}]})
        out = await _probe_full(list(targets), trigger=trigger, detail=str(body.get("detail") or ""))
        _audit(p, "system.probe", detail={"mode": mode, "trigger": trigger, "targets": targets, "run_id": out["run_id"]})
        return {"ok": True, **out}

